WITH SAMPSET AS
(
SELECT /*+materialize*/ DISTINCT SAFE_NUMBER, DEFENDANT_NAME, DEFENDANT_STREET_ADDRESS, DEFENDANT_CITY, DEFENDANT_STATE, DEFENDANT_ZIP_CODE, UNIQUE_CASE_ID FROM CORE_DATA.BANKRUPTCY
WHERE CREATE_DATE>SYSDATE-7
and deleted_by_import is null and deleted_by_editing_tool is null
),
GROUP_EVAL_OUTPUT AS
(
SELECT   /*+materialize*/
DISTINCT
MAX(A.BK_MATCH_IND) OVER (PARTITION BY A.CS_COMPANY_ID ORDER BY A.BK_MATCH_IND ASC NULLS LAST) AS BK_MATCH_IND,
MAX(A.UNIQUE_CASE_ID) OVER (PARTITION BY A.CS_COMPANY_ID ORDER BY A.UNIQUE_CASE_ID ASC NULLS LAST) AS UNIQUE_CASE_ID,
MAX(A.HAS_BK_CASE_ID) OVER (PARTITION BY A.CS_COMPANY_ID ORDER BY A.HAS_BK_CASE_ID ASC NULLS LAST) AS HAS_BK_CASE_ID,
A.DEFENDANT_NAME, A.DEFENDANT_STREET_ADDRESS, A.DEFENDANT_CITY, A.DEFENDANT_STATE, A.DEFENDANT_ZIP_CODE,
COMPREL_GROUP_ID, PARENTID, COMPANYID, CS_COMPANY_ID, COMPANY_NAME, COMPANY_TYPE, COMPANY_ADDRESS, COMPANY_CITY, COMPANY_STATE, COMPANY_ZIPCODE
FROM
(
SELECT DISTINCT CASE WHEN A.SAFE_NUMBER = C.CS_COMPANY_ID THEN 'BK MATCH SN' ELSE NULL END AS BK_MATCH_IND, A.UNIQUE_CASE_ID,
CASE WHEN EXISTS
    (SELECT 1 FROM CORE_DATA.BANKRUPTCY Z WHERE C.CS_COMPANY_ID = Z.SAFE_NUMBER AND A.UNIQUE_CASE_ID = Z.UNIQUE_CASE_ID AND
    Z.DELETED_BY_EDITING_TOOL IS NULL AND Z.DELETED_BY_IMPORT IS NULL)
    THEN A.UNIQUE_CASE_ID ELSE NULL END AS HAS_BK_CASE_ID,
A.COMPREL_GROUP_ID,
A.DEFENDANT_NAME, A.DEFENDANT_STREET_ADDRESS, A.DEFENDANT_CITY, A.DEFENDANT_STATE, A.DEFENDANT_ZIP_CODE,
C.PARENTID, C.COMPANYID, C.CS_COMPANY_ID, C.COMPANY_NAME, C.COMPANY_TYPE, C.COMPANY_ADDRESS, C.COMPANY_CITY, C.COMPANY_STATE, C.COMPANY_ZIPCODE FROM
(
SELECT A.*,
CASE WHEN B.COMPANY_TYPE = 'BRANCH' THEN B.PARENTID ELSE B.COMPANYID END AS COMPREL_GROUP_ID
FROM SAMPSET A
LEFT JOIN CORE_DATA.COMPANY_RELATIONSHIP B
ON A.SAFE_NUMBER = B.CS_COMPANY_ID
AND B.DELETED_BY_EDITING_TOOL IS NULL AND B.DELETED_BY_IMPORT IS NULL
) A
INNER JOIN CORE_DATA.COMPANY_RELATIONSHIP C
ON ((A.COMPREL_GROUP_ID = C.COMPANYID) OR (A.COMPREL_GROUP_ID = C.PARENTID AND C.COMPANY_TYPE = 'BRANCH'))
AND C.DELETED_BY_EDITING_TOOL IS NULL AND C.DELETED_BY_IMPORT IS NULL
) A
),
SPLIT_CASES AS
(
SELECT /*+materialize*/   * FROM GROUP_EVAL_OUTPUT WHERE COMPREL_GROUP_ID IN (
SELECT COMPREL_GROUP_ID FROM GROUP_EVAL_OUTPUT A
GROUP BY COMPREL_GROUP_ID
HAVING COUNT(HAS_BK_CASE_ID)>1
)
),
split_cases_s2 as
(
SELECT /*+materialize*/  * FROM
(
SELECT
ROW_NUMBER() OVER (PARTITION BY A.COMPREL_GROUP_ID, GREATEST(A.CS_COMPANY_ID, B.CS_COMPANY_ID ),LEAST(A.CS_COMPANY_ID, B.CS_COMPANY_ID ) ORDER BY A.BK_MATCH_IND DESC NULLS LAST) AS RN,
    A.BK_MATCH_IND,
    A.UNIQUE_CASE_ID,
    A.HAS_BK_CASE_ID,
    A.CS_COMPANY_ID   AS SAFE_NUMBER_1,
    B.CS_COMPANY_ID AS SAFE_NUMBER_2,
    A.DEFENDANT_NAME,
    A.DEFENDANT_STREET_ADDRESS,
    A.DEFENDANT_CITY,
    A.DEFENDANT_STATE,
    A.DEFENDANT_ZIP_CODE,
    A.COMPREL_GROUP_ID,
    A.PARENTID,
    A.COMPANYID AS COMPANYID_1,
    A.COMPANY_NAME AS COMPANY_NAME_1,
    A.COMPANY_TYPE AS COMPANY_TYPE_1,
    A.COMPANY_ADDRESS AS COMPANY_ADDRESS_1,
    A.COMPANY_CITY AS COMPANY_CITY_1,
    A.COMPANY_STATE AS COMPANY_STATE_1,
    A.COMPANY_ZIPCODE AS COMPANY_ZIPCODE_1,
    B.COMPANYID AS COMPANYID_2,
    B.COMPANY_NAME AS COMPANY_NAME_2,
    B.COMPANY_TYPE AS COMPANY_TYPE_2,
    B.COMPANY_ADDRESS AS COMPANY_ADDRESS_2,
    B.COMPANY_CITY AS COMPANY_CITY_2,
    B.COMPANY_STATE AS COMPANY_STATE_2,
    B.COMPANY_ZIPCODE AS COMPANY_ZIPCODE_2
FROM
    SPLIT_CASES A
    INNER JOIN SPLIT_CASES B ON A.HAS_BK_CASE_ID = B.HAS_BK_CASE_ID
                                AND A.COMPREL_GROUP_ID = B.COMPREL_GROUP_ID
                                AND A.CS_COMPANY_ID != B.CS_COMPANY_ID
ORDER BY
    A.COMPREL_GROUP_ID
    )
    WHERE RN =1
    ),
    split_cases_s3 as
    (
    select /*+materialize*/  a.safe_number_1, a.safe_number_2, a.UNIQUE_CASE_ID, b.ROW_UNIQUE_ID from split_cases_s2 a
inner join  core_data.bankruptcy b
on a.UNIQUE_CASE_ID = b.UNIQUE_CASE_ID
and b.deleted_by_editing_tool is null and b.deleted_by_import is null
    ),
    gen_split_case_set as
    (
    select safe_number_1 as safe_number, UNIQUE_CASE_ID, ROW_UNIQUE_ID from split_cases_s3
    union
select safe_number_2 as safe_number, UNIQUE_CASE_ID, ROW_UNIQUE_ID from split_cases_s3
),
gen_split_case_adds as
(
select /*+materialize*/  a.SAFE_NUMBER, a.UNIQUE_CASE_ID, a.ROW_UNIQUE_ID from gen_split_case_set a
left join core_data.bankruptcy c
on a.safe_number = c.safe_number and a.UNIQUE_CASE_ID = c.UNIQUE_CASE_ID and a.ROW_UNIQUE_ID = c.ROW_UNIQUE_ID and c.deleted_by_editing_tool is null and c.deleted_by_import is null
where c.rowid is null
order by a.UNIQUE_CASE_ID, a.safe_number
),
add_bk_rows_output as
(
select  /*+materialize*/  distinct a.row_unique_id as RMSID,
a.SAFE_NUMBER,
b.DEFENDANT_TYPE,
b.ALIAS_TYPE,
b.ASSOCIATION_CODE,
b.COURTID,
b.CASE_NUMBER,
b.FILING_TYPES,
b.ORIGINAL_CHAPTER,
b.FILING_DATE,
b.RELEASE_DATE,
b.ASSETS,
b.LAW_FIRM_ATTORNEY_TRUSTEE_NAME AS LAW_FIRM_ATTO_TRUSTEE_NAME,
b.ATTORNEY_NAME,
b.ATTORNEY_PHONE,
b.SCH_341_DATE,
b.JUDGES_INITIALS,
b.OTHER_CASE_NUMBER,
b.DEFENDANT_ID,
b.DEFENDANT_NAME,
b.DEFENDANT_NAME_GENERATION_CODE AS DEFENDANT_NAME_GENERAT_CODE,
b.DEFENDANT_STREET_ADDRESS,
b.DEFENDANT_CITY,
b.DEFENDANT_STATE,
b.DEFENDANT_ZIP_CODE,
b.DATE_RECORD_UPLOADED,
b.CASE_TYPE,
b.UNIQUE_CASE_ID,
b.CURRENT_CHAPTER,
b.PREVIOUS_CHAPTER,
b.ATTORNEY_ADDRESS,
b.ATTORNEY_CITY,
b.ATTORNEY_STATE,
b.ATTORNEY_ZIP,
b.ASSETS_AVAILABLE_FOR_DISTRIBUT AS ASSETS_AVAIL_FOR_DISTRIBUT,
b.ACTION_TYPE_ID,
b.SCH_341_TIME,
b.POCDATE,
b.DELETED_BY_IMPORT,
b.DELETED_BY_EDITING_TOOL
from gen_split_case_adds a
inner join core_data.bankruptcy b
on a.unique_case_id = b.unique_case_id
and a.row_unique_id = b.row_unique_id
)
select * from add_bk_rows_output





