with cte as
(
Select b.RMSID,a.* from core_data.bankruptcy a
left join source_legal_data.source_bankruptcy b
on a.Row_unique_id = b.Row_unique_id
where TO_DATE(a.Filing_date, 'DD-MON-RR') > TO_DATE('01-JAN-2016','DD-MON-YYYY')
AND DELETED_BY_EDITING_TOOL is not null
)
Select
distinct C.RMSID,
c.SAFE_NUMBER,
c.CREATE_DATE,
c.CREATE_BATCH_ID,
c.LAST_UPDATE_DATE,
c.LAST_BATCH_ID,
c.DEFENDANT_TYPE,
c.ALIAS_TYPE,
c.ASSOCIATION_CODE,
c.COURTID,
c.CASE_NUMBER,
c.FILING_TYPES,
c.ORIGINAL_CHAPTER,
c.FILING_DATE,
c.RELEASE_DATE,
c.ASSETS,
c.LAW_FIRM_ATTORNEY_TRUSTEE_NAME,
c.ATTORNEY_NAME,
c.ATTORNEY_PHONE,
c.SCH_341_DATE,
c.JUDGES_INITIALS,
c.OTHER_CASE_NUMBER,
c.DEFENDANT_ID,
c.DEFENDANT_NAME,
c.DEFENDANT_NAME_GENERATION_CODE,
c.DEFENDANT_STREET_ADDRESS,
c.DEFENDANT_CITY,
c.DEFENDANT_STATE,
c.DEFENDANT_ZIP_CODE,
c.DATE_RECORD_UPLOADED,
c.CASE_TYPE,
c.UNIQUE_CASE_ID,
c.CURRENT_CHAPTER,
c.PREVIOUS_CHAPTER,
c.ATTORNEY_ADDRESS,
c.ATTORNEY_CITY,
c.ATTORNEY_STATE,
c.ATTORNEY_ZIP,
c.ASSETS_AVAILABLE_FOR_DISTRIBUT,
c.ACTION_TYPE_ID,
c.SCH_341_TIME,
c.POCDATE
--count(distinct c.RMSID)
from cte c
Join source_legal_data.bankruptcy_data_rollup d
on c.RMSID = d.RMSID
where d.DELETED_BY_IMPORT is null and d.DELETED_BY_EDITING_TOOL is null
